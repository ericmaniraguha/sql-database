-- 1. Concept Overview
-- =============================================================================
-- MySQL is one of the world's most widely deployed open-source RDBMSs, default
-- to the ACID-compliant InnoDB storage engine. MySQL includes proprietary 
-- convenience extensions like GROUP_CONCAT and ON DUPLICATE KEY UPDATE.

-- =============================================================================
-- 2. AUTO_INCREMENT and LAST_INSERT_ID()
-- =============================================================================
-- In MySQL, surrogate primary keys use the AUTO_INCREMENT attribute:

/*
