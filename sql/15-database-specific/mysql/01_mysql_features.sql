-- =============================================================================
-- 3. Upsert: INSERT ... ON DUPLICATE KEY UPDATE
-- =============================================================================
-- Inserts a row if the primary/unique key does not exist; if it already exists,
-- updates the existing row instead of throwing an error:

/*
INSERT INTO departments (department_id, department_code, department_name, budget)
VALUES (1, 'CS', 'Computer Science & Software Eng', 950000.00)
ON DUPLICATE KEY UPDATE
    department_name = VALUES(department_name),
    budget          = VALUES(budget);
*/

-- =============================================================================
-- 4. Aggregating Strings with GROUP_CONCAT()
-- =============================================================================
-- Concatenates values from multiple rows into a single delimited string per group:

/*
SELECT 
    d.department_name,
    GROUP_CONCAT(c.course_code ORDER BY c.course_code ASC SEPARATOR ', ') AS offered_courses
FROM departments d
INNER JOIN courses c ON d.department_id = c.department_id
GROUP BY d.department_id, d.department_name;
*/

-- =============================================================================
-- 5. Storage Engines: InnoDB vs MyISAM
-- =============================================================================
-- - InnoDB (Default): Fully ACID compliant, supports Foreign Keys, row-level locking,
--   and crash recovery. Always use InnoDB for transactional applications.
-- - MyISAM (Legacy): No transactions, table-level locking only, no foreign keys. 
--   Not recommended for modern production databases.

-- Inspect table engine and status:
/*
SHOW TABLE STATUS LIKE 'students';
*/

