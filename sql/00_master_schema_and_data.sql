-- -----------------------------------------------------------------------------
-- Step 1: Clean Up Existing Tables (Drop in reverse dependency order)
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS course_prerequisites;
DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS instructors;
DROP TABLE IF EXISTS departments;

-- -----------------------------------------------------------------------------
-- Step 2: Create Relational Tables
-- -----------------------------------------------------------------------------

-- 1. Departments
CREATE TABLE departments (
    department_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code     VARCHAR(10)   NOT NULL UNIQUE,
    department_name     VARCHAR(100)  NOT NULL UNIQUE,
    building            VARCHAR(50),
    budget              DECIMAL(12, 2) DEFAULT 0.00 CHECK (budget >= 0.00),
    established_year    INT
);

-- 2. Instructors
CREATE TABLE instructors (
    instructor_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name          VARCHAR(50)   NOT NULL,
    last_name           VARCHAR(50)   NOT NULL,
    email               VARCHAR(100)  NOT NULL UNIQUE,
    hire_date           DATE          NOT NULL,
    department_id       INT,
    salary              DECIMAL(10, 2) CHECK (salary >= 20000.00),
    academic_rank       VARCHAR(30)   DEFAULT 'Lecturer',
    office_number       VARCHAR(20),
    mentor_id           INT,
    CONSTRAINT fk_instructors_dept FOREIGN KEY (department_id) 
        REFERENCES departments(department_id) ON DELETE SET NULL,
    CONSTRAINT fk_instructors_mentor FOREIGN KEY (mentor_id) 
        REFERENCES instructors(instructor_id) ON DELETE SET NULL
);

-- 3. Students
CREATE TABLE students (
    student_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name          VARCHAR(50)   NOT NULL,
    last_name           VARCHAR(50)   NOT NULL,
    email               VARCHAR(100)  NOT NULL UNIQUE,
    birth_date          DATE          NOT NULL,
    enrollment_date     DATE          DEFAULT CURRENT_DATE,
    department_id       INT,
    gpa                 DECIMAL(3, 2) DEFAULT 0.00 CHECK (gpa >= 0.00 AND gpa <= 4.00),
    status              VARCHAR(20)   DEFAULT 'Active' 
        CHECK (status IN ('Active', 'Suspended', 'Graduated', 'Withdrawn', 'Academic Warning')),
    CONSTRAINT fk_students_dept FOREIGN KEY (department_id) 
        REFERENCES departments(department_id) ON DELETE RESTRICT
);

-- 4. Courses
CREATE TABLE courses (
    course_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code         VARCHAR(15)   NOT NULL UNIQUE,
    course_name         VARCHAR(120)  NOT NULL,
    credits             INT           DEFAULT 3 CHECK (credits BETWEEN 1 AND 6),
    department_id       INT           NOT NULL,
    instructor_id       INT,
    CONSTRAINT fk_courses_dept FOREIGN KEY (department_id) 
        REFERENCES departments(department_id) ON DELETE RESTRICT,
    CONSTRAINT fk_courses_instructor FOREIGN KEY (instructor_id) 
        REFERENCES instructors(instructor_id) ON DELETE SET NULL
);

-- 5. Course Prerequisites
CREATE TABLE course_prerequisites (
    course_id               INT NOT NULL,
    prerequisite_course_id  INT NOT NULL,
    minimum_grade           VARCHAR(2) DEFAULT 'C',
    CONSTRAINT pk_course_prerequisites PRIMARY KEY (course_id, prerequisite_course_id),
    CONSTRAINT fk_cp_target FOREIGN KEY (course_id) 
        REFERENCES courses(course_id) ON DELETE CASCADE,
    CONSTRAINT fk_cp_prereq FOREIGN KEY (prerequisite_course_id) 
        REFERENCES courses(course_id) ON DELETE CASCADE
);

-- 6. Enrollments
CREATE TABLE enrollments (
    enrollment_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          INT           NOT NULL,
    course_id           INT           NOT NULL,
    semester            VARCHAR(10)   NOT NULL CHECK (semester IN ('Fall', 'Spring', 'Summer')),
    academic_year       INT           NOT NULL,
    numeric_grade       DECIMAL(5, 2) CHECK (numeric_grade BETWEEN 0.00 AND 100.00),
    letter_grade        VARCHAR(2),
    status              VARCHAR(20)   DEFAULT 'Enrolled' 
        CHECK (status IN ('Enrolled', 'Completed', 'Dropped', 'In Progress')),
    CONSTRAINT uq_student_course_term UNIQUE (student_id, course_id, semester, academic_year),
    CONSTRAINT fk_enrollments_student FOREIGN KEY (student_id) 
        REFERENCES students(student_id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_course FOREIGN KEY (course_id) 
        REFERENCES courses(course_id) ON DELETE RESTRICT
);

