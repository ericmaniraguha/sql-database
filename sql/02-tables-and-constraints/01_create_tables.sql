-- =============================================================================
-- 1. Concept Overview
-- =============================================================================
-- A table is the primary database object used to store data in rows (records)
-- and columns (attributes). Every column must be assigned an appropriate data type
-- to enforce storage efficiency and data domain validation.
--
-- Common Standard Data Types:
-- - INT / INTEGER: Whole numbers (-2^31 to 2^31 - 1)
-- - VARCHAR(n): Variable-length character string up to length n
-- - DECIMAL(p, s) / NUMERIC(p, s): Exact fixed-point numeric (p = precision, s = scale)
-- - DATE: Calendar date (YYYY-MM-DD)
-- - TIMESTAMP: Date and time with fractional seconds
-- - BOOLEAN: TRUE / FALSE (in MySQL stored as TINYINT(1))

-- Drop tables in reverse dependency order to avoid foreign key violations
DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS instructors;
DROP TABLE IF EXISTS departments;

-- =============================================================================
-- 2. Departments Table
-- =============================================================================
CREATE TABLE departments (
    department_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Standard ANSI / Postgres / Oracle 12c+
    -- For MySQL replace above with: department_id INT AUTO_INCREMENT PRIMARY KEY,
    department_code     VARCHAR(10)  NOT NULL,
    department_name     VARCHAR(100) NOT NULL,
    building            VARCHAR(50),
    budget              DECIMAL(12, 2) DEFAULT 0.00,
    established_year    INT
);

-- =============================================================================
-- 3. Instructors Table
-- =============================================================================
CREATE TABLE instructors (
    instructor_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- MySQL: instructor_id INT AUTO_INCREMENT PRIMARY KEY,
    first_name          VARCHAR(50)  NOT NULL,
    last_name           VARCHAR(50)  NOT NULL,
    email               VARCHAR(100) NOT NULL,
    hire_date           DATE         NOT NULL,
    department_id       INT,
    salary              DECIMAL(10, 2),
    academic_rank       VARCHAR(30)  DEFAULT 'Lecturer'
);

-- =============================================================================
-- 4. Students Table
-- =============================================================================
CREATE TABLE students (
    student_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- MySQL: student_id INT AUTO_INCREMENT PRIMARY KEY,
    first_name          VARCHAR(50)  NOT NULL,
    last_name           VARCHAR(50)  NOT NULL,
    email               VARCHAR(100) NOT NULL,
    birth_date          DATE         NOT NULL,
    enrollment_date     DATE         DEFAULT CURRENT_DATE,
    department_id       INT,
    gpa                 DECIMAL(3, 2) DEFAULT 0.00,
    status              VARCHAR(20)  DEFAULT 'Active'
);

-- =============================================================================
-- 5. Courses Table
-- =============================================================================
CREATE TABLE courses (
    course_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- MySQL: course_id INT AUTO_INCREMENT PRIMARY KEY,
    course_code         VARCHAR(15)  NOT NULL,
    course_name         VARCHAR(120) NOT NULL,
    credits             INT          DEFAULT 3,
    department_id       INT          NOT NULL,
    instructor_id       INT
);

-- =============================================================================
-- 6. Enrollments Table (Associative Entity)
-- =============================================================================
CREATE TABLE enrollments (
    enrollment_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- MySQL: enrollment_id INT AUTO_INCREMENT PRIMARY KEY,
    student_id          INT          NOT NULL,
    course_id           INT          NOT NULL,
    semester            VARCHAR(10)  NOT NULL, -- 'Fall', 'Spring', 'Summer'
    academic_year       INT          NOT NULL,
    numeric_grade       DECIMAL(5, 2),
    letter_grade        VARCHAR(2),
    status              VARCHAR(20)  DEFAULT 'Enrolled'
);

